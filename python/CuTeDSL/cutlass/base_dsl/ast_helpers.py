def loop_selector(
    start: Any,
    stop: Any,
    step: Any,
    *,
    write_args: list[Any] = [],
    full_write_args_count: int = 0,
    write_args_names: list[str] = [],
    unroll: int = -1,
    unroll_full: bool = False,
    prefetch_stages: int | None = None,
    vectorize: int | None = None,
    at_least_once: bool = False,
) -> Callable[..., Any]:
    from .typing import Integer

    def _maybe_upcast(value: Any) -> Any:
        if isinstance(value, Integer):
            value = value.ir_value()

        return value

    start = _maybe_upcast(start)
    stop = _maybe_upcast(stop)
    step = _maybe_upcast(step)

    def ir_loop(func: Callable[..., Any]) -> Any:
        return executor.for_execute(
            func,
            start,
            stop,
            step,
            write_args=write_args,
            full_write_args_count=full_write_args_count,
            write_args_names=write_args_names,
            unroll=unroll,
            unroll_full=unroll_full,
            prefetch_stages=prefetch_stages,
            vectorize=vectorize,
            at_least_once=at_least_once,
        )

    return ir_loop


def _public_type_name(obj: object) -> str:
    """The user-facing class name of *obj*: the first class in its MRO that is
    not a ``_``-prefixed implementation class (``_Layout`` -> ``Layout``)."""
    for cls in type(obj).__mro__:
        if not cls.__name__.startswith("_"):
            return cls.__name__
    return type(obj).__name__


def truth_of(pred: Any) -> Any:
    """Trace-time normalisation of a predicate (if/while/ternary/not/and/or/bool()).

    Returns *pred* when its truth is decided at run time: a Numeric backed by
    an SSA value or a scalar (integer/index/float typed) SSA value, the
    latter wrapped as an ``ArithValue`` so every consumer sees one shape.
    A Numeric is first re-read through its ref, exactly as every
    ``@dsl_user_op`` argument is: a pyir-tracked binding rebound inside staged
    control flow must not be folded on its stale payload, and taking
    ``.value`` directly would reuse the SSA value from the region that wrote
    it and break dominance.  Python numbers pass through as well --
    ``Boolean`` gives them Python's truth, and a watched meta wrapper must
    reach it so its bake is recorded.

    Everything else is decided now, at trace time, by Python's own rules: a
    Numeric holding a Python payload, a str, None, a user object, and a
    tuple/list/dict/set -- whether or not it holds staged leaves, its truth is
    its length and never reads an element.  A DSL object that is not a scalar
    (Layout, Tensor, Pointer, ...) -- whether it exposes
    ``__extract_mlir_values__`` or is itself a non-scalar-typed SSA value --
    has no truth value and is refused.
    """
    from .typing import Numeric
    from .._mlir_helpers.arith import ArithValue

    cond, branch_weights = _extract_condition_branch_weights(pred)
    if branch_weights is not None:
        # A ``weighted_condition`` marker: its truth is its condition's. The
        # weights are read off the marker by ``if_executor`` /
        # ``ifExp_executor`` before they normalise the condition.
        return truth_of(cond)
    if isinstance(pred, Numeric):
        from .pyir_corewalk import _pyir_auto_load_arg

        pred = _pyir_auto_load_arg(pred)
        if isinstance(pred.value, (bool, int, float)):
            return bool(pred)
        return pred
    if isinstance(pred, (bool, int, float)):
        return pred
    if hasattr(pred, "__extract_mlir_values__") and not isinstance(pred, type):
        raise DSLUserCodeTypeError(
            DiagId.TYPE_TRUTH_OF_DSL_OBJECT, type=_public_type_name(pred)
        )
    if isinstance(pred, ir.Value):
        if isinstance(pred, ArithValue):
            return pred
        if isinstance(pred.type, (ir.IntegerType, ir.IndexType, ir.FloatType)):
            # A hand-built scalar SSA value tests like ``x.ir_value()`` does.
            return ArithValue(pred)
        raise DSLUserCodeTypeError(
            DiagId.TYPE_TRUTH_OF_DSL_OBJECT, type=_public_type_name(pred)
        )
    # A user object's truth test runs its plain ``__bool__``/``__len__`` with
    # no ``ast.Call`` for the wrap pass; the boundary observes it.
    from .pyir_callee_rewrite import _pyir_boundary_observe_truth

    return _pyir_boundary_observe_truth(pred)


def if_selector(pred: Any, write_args: list[Any] = []) -> Callable[..., Any]:
    # Witness a trace-time fold of a watched META predicate so a later staged
    # write of its source places refuses loudly. No-op for other predicates.
    # The predicate itself is normalised by ``if_executor``.
    _pyir_witness_predicate_fold(pred)

    def ir_loop(func: Callable[..., Any]) -> Any:
        return func(pred, *write_args)

    return ir_loop


def while_selector(*, write_args: list[Any] = []) -> Callable[..., Any]:
    def ir_while_loop(func: Callable[..., Any]) -> Any:
        return func(*write_args)

    return ir_while_loop


def while_executor(
    while_before_block: Callable[..., Any],
    while_after_block: Callable[..., Any],
    write_args: list[Any] = [],
    full_write_args_count: int = 0,
    write_args_names: list[str] = [],
) -> Any:
    return executor.while_execute(
        while_before_block,
        while_after_block,
        write_args,
        full_write_args_count,
        write_args_names,
    )


def if_executor(
    pred: Any,
    then_block: Callable[..., Any],
    else_block: Callable[..., Any] | None = None,
    write_args: list[Any] = [],
    full_write_args_count: int = 0,
    write_args_names: list[str] = [],
    branch_weights: Optional[tuple[int, int]] = None,
) -> Any:
    pred, wrapped_branch_weights = _extract_condition_branch_weights(pred)
    if branch_weights is None:
        branch_weights = wrapped_branch_weights

    from .typing import Numeric

    pred = truth_of(pred)
    if isinstance(pred, Numeric):
        pred = pred.value

    return executor.if_execute(
        pred,
        then_block,
        else_block,
        write_args,
        full_write_args_count,
        write_args_names,
        branch_weights=branch_weights,
    )


def ifExp_executor(
    *,
    pred: Any,
    block_args: tuple[Any, ...],
    then_block: Callable[..., Any],
    else_block: Callable[..., Any],
    branch_weights: Optional[tuple[int, int]] = None,
) -> Any:
    pred, wrapped_branch_weights = _extract_condition_branch_weights(pred)
    if branch_weights is None:
        branch_weights = wrapped_branch_weights

    # Same witness as ``if_selector``: a watched META predicate folded here is
    # a structural consumption of its source places (and a read that refuses
    # when a place was mutated on an arm this expression is outside of).
    # PyIR only: the legacy path has no watched predicates to witness.
    if is_pyir_enabled():
        _pyir_witness_predicate_fold(pred)

    from .typing import Numeric

    pred = truth_of(pred)
    if isinstance(pred, (Numeric, ir.Value)):
        return executor.ifexp_execute(
            pred, block_args, then_block, else_block, branch_weights=branch_weights
        )
    return then_block(*block_args) if pred else else_block(*block_args)


