class _BoolOpTerm:
    """One reached operand in the base preprocessor's comparison chain."""

    __slots__ = ("combine", "value", "stop")
    stop: bool

    def __init__(self, combine: Callable[[Any, Any], Any] | None, value: Any) -> None:
        self.combine = combine
        self.value = value

    def __bool__(self) -> bool:
        return self.value is not self.stop

    def __lt__(self, rhs: "_BoolOpTerm") -> "_BoolOpTerm":
        """Python retains rhs as the left operand of the next comparison."""
        assert rhs.combine is not None
        rhs.value = rhs.combine(self.value, rhs.value)
        rhs.stop = self.stop
        return rhs


class _BoolOpStart:
    __slots__ = ("stop",)

    def __init__(self, stop: bool) -> None:
        self.stop = stop

    def __lt__(self, first: _BoolOpTerm) -> _BoolOpTerm:
        first.stop = self.stop
        return first


_and_start = _BoolOpStart(False)
_or_start = _BoolOpStart(True)


def _extract_condition_branch_weights(
    pred: Any,
) -> tuple[Any, Optional[tuple[int, int]]]:
    """A ``weighted_condition`` marker as its condition and ``(then, else)``
    weights; any other predicate is returned as is, with ``None``."""
    branch_weights = getattr(pred, _DSL_BRANCH_WEIGHTS_ATTR, None)
    if branch_weights is None or not hasattr(pred, _DSL_CONDITION_ATTR):
        return pred, None

    weights = tuple(branch_weights)
    if len(weights) != 2:
        return pred, None

    return getattr(pred, _DSL_CONDITION_ATTR), (weights[0], weights[1])


class Executor:
    """
    The Executor class handles dynamic and compile-time (constexpr) execution
    of "for" loops and "if-else-elif" statements.

    Methods:
        set_functions:  Assigns the functions for checking loop bounds and
                        conditional evaluation.

        for_execute: Generates MLIR for OP
        while_execute: Generates MLIR while OP
        if_execute: generate MLIR if OP
    """

    def __init__(self) -> None:
        self._is_dynamic_expression: Callable[..., Any] | None = None
        self._loop_execute_range_dynamic: Callable[..., Any] | None = None
        self._if_dynamic: Callable[..., Any] | None = None
        self._while_dynamic: Callable[..., Any] | None = None
        self._compare_executor: Callable[..., Any] | None = None
        self._builtin_redirector: Callable[..., Any] | None = None
        self._ifexp_dynamic: Callable[..., Any] | None = None
        self._and_: Callable[..., Any] | None = None
        self._or_: Callable[..., Any] | None = None
        self._not_: Callable[..., Any] | None = None

    @staticmethod
    def _default_builtin_redirector(fcn: Callable[..., Any]) -> Callable[..., Any]:
        # Default to no redirect
        return fcn

    @staticmethod
    def _accepts_keyword(func: Callable[..., Any], keyword: str) -> bool:
        try:
            parameters = inspect.signature(func).parameters
        except (TypeError, ValueError):
            return True

        return any(
            param.kind == inspect.Parameter.VAR_KEYWORD or name == keyword
            for name, param in parameters.items()
        )

    @classmethod
    def _with_optional_branch_weights(
        cls, func: Callable[..., Any]
    ) -> Callable[..., Any]:
        if cls._accepts_keyword(func, "branch_weights"):
            return func

        @wraps(func)
        def wrapped(
            *args: Any,
            branch_weights: Optional[tuple[int, int]] = None,
            **kwargs: Any,
        ) -> Any:
            if branch_weights is not None:
                raise TypeError(f"{func.__name__} does not accept branch_weights")
            return func(*args, **kwargs)

        return wrapped

    def set_functions(
        self,
        *,
        is_dynamic_expression: Callable[..., Any],
        loop_execute_range_dynamic: Callable[..., Any],
        if_dynamic: Callable[..., Any],
        while_dynamic: Callable[..., Any],
        compare_executor: Callable[..., Any],
        builtin_redirector: Callable[..., Any] = _default_builtin_redirector,
        ifexp_dynamic: Callable[..., Any] | None = None,
        and_: Callable[..., Any] | None = None,
        or_: Callable[..., Any] | None = None,
        not_: Callable[..., Any] | None = None,
    ) -> None:
        self._is_dynamic_expression = is_dynamic_expression
        self._loop_execute_range_dynamic = loop_execute_range_dynamic
        self._if_dynamic = self._with_optional_branch_weights(if_dynamic)
        self._while_dynamic = while_dynamic
        self._compare_executor = compare_executor
        self._builtin_redirector = builtin_redirector
        self._ifexp_dynamic = (
            self._with_optional_branch_weights(ifexp_dynamic)
            if ifexp_dynamic is not None
            else None
        )
        self._and_ = and_
        self._or_ = or_
        self._not_ = not_

    def for_execute(
        self,
        func: Callable[..., Any],
        start: Any,
        stop: Any,
        step: Any,
        write_args: list[Any] = [],
        full_write_args_count: int = 0,
        write_args_names: list[str] = [],
        unroll: int = -1,
        unroll_full: bool = False,
        prefetch_stages: int | None = None,
        vectorize: int | None = None,
        at_least_once: bool = False,
    ) -> Any:
        assert self._loop_execute_range_dynamic, (
            "Functions must be set before execution."
        )
        log().debug("start [%s] stop [%s] step [%s]", start, stop, step)

        return self._loop_execute_range_dynamic(
            func,
            start,
            stop,
            step,
            write_args=write_args,
            full_write_args_count=full_write_args_count,
            write_args_names=write_args_names,
            unroll=unroll,
            unroll_full=unroll_full,
            prefetch_stages=prefetch_stages,
            vectorize=vectorize,
            at_least_once=at_least_once,
        )

    def if_execute(
        self,
        pred: Any,
        then_block: Callable[..., Any],
        else_block: Callable[..., Any] | None = None,
        write_args: list[Any] = [],
        full_write_args_count: int = 0,
        write_args_names: list[str] = [],
        branch_weights: Optional[tuple[int, int]] = None,
    ) -> Any:
        assert self._if_dynamic, "Functions must be set before execution."

        # MLIR generation
        return self._if_dynamic(
            pred,
            then_block,
            else_block,
            write_args,
            full_write_args_count,
            write_args_names,
            branch_weights=branch_weights,
        )

    def while_execute(
        self,
        while_before_block: Callable[..., Any],
        while_after_block: Callable[..., Any],
        write_args: list[Any] = [],
        full_write_args_count: int = 0,
        write_args_names: list[str] = [],
    ) -> Any:
        assert self._while_dynamic, "Functions must be set before execution."
        return self._while_dynamic(
            while_before_block,
            while_after_block,
            write_args,
            full_write_args_count,
            write_args_names,
        )

    def ifexp_execute(
        self,
        pred: Any,
        block_args: tuple[Any, ...],
        then_block: Callable[..., Any],
        else_block: Callable[..., Any],
        branch_weights: Optional[tuple[int, int]] = None,
    ) -> Any:
        assert self._ifexp_dynamic, "Functions must be set before execution."
        return self._ifexp_dynamic(
            pred, block_args, then_block, else_block, branch_weights=branch_weights
        )

    # ``and`` / ``or`` / ``not`` over a staged operand: the DSL's ``and_`` /
    # ``or_`` / ``not_`` when registered, else Python's own operator.
    def logical_and(self, lhs: Any, rhs: Any) -> Any:
        if self._and_ is None:
            return lhs and rhs
        return self._and_(lhs, rhs)

    def logical_or(self, lhs: Any, rhs: Any) -> Any:
        if self._or_ is None:
            return lhs or rhs
        return self._or_(lhs, rhs)

    def logical_not(self, value: Any) -> Any:
        if self._not_ is None:
            return not value
        return self._not_(value)


