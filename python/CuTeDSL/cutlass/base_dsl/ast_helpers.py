class range:
    """Trace-time representation of a dynamic DSL range."""

    @overload
    def __init__(
        self,
        stop: Any,
        /,
        *,
        unroll: int = -1,
        unroll_full: bool = False,
        prefetch_stages: int | None = None,
        pipelining: int | None = None,
        vectorize: int | None = None,
        at_least_once: bool = False,
    ) -> None: ...

    @overload
    def __init__(
        self,
        start: Any,
        stop: Any,
        /,
        *,
        unroll: int = -1,
        unroll_full: bool = False,
        prefetch_stages: int | None = None,
        pipelining: int | None = None,
        vectorize: int | None = None,
        at_least_once: bool = False,
    ) -> None: ...

    @overload
    def __init__(
        self,
        start: Any,
        stop: Any,
        step: Any,
        /,
        *,
        unroll: int = -1,
        unroll_full: bool = False,
        prefetch_stages: int | None = None,
        pipelining: int | None = None,
        vectorize: int | None = None,
        at_least_once: bool = False,
    ) -> None: ...

    def __init__(
        self,
        *args: Any,
        unroll: int = -1,
        unroll_full: bool = False,
        prefetch_stages: int | None = None,
        pipelining: int | None = None,
        vectorize: int | None = None,
        at_least_once: bool = False,
    ) -> None:
        if len(args) not in (1, 2, 3):
            raise DSLUserCodeError(DiagId.UNSUP_RANGE_ARGS)
        self.start = 0 if len(args) == 1 else args[0]
        self.stop = args[0] if len(args) == 1 else args[1]
        self.step = args[2] if len(args) == 3 else 1
        self.unroll = unroll
        self.unroll_full = unroll_full
        if pipelining is not None:
            _warn_deprecated(
                "pipelining is deprecated, use prefetch_stages instead",
                every_call=True,
            )
        self.prefetch_stages = pipelining if pipelining is not None else prefetch_stages
        self.vectorize = vectorize
        self.at_least_once = at_least_once

    def __iter__(self) -> Iterator[int]:
        # Only a ``for`` statement in a decorated body is rewritten into a
        # staged loop; any other iteration is the author's, not a DSL bug.
        raise DSLUserCodeError(DiagId.PHASE_DYNAMIC_RANGE_ITERATED_BY_PYTHON)


