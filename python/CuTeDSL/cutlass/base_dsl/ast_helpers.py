def _range_value_check(
    args: tuple[Any, ...], *, warning_stacklevel: int
) -> tuple[int, int, int]:
    """Validate constexpr bounds with call-site-specific warning attribution."""
    if len(args) not in (1, 2, 3):
        raise DSLUserCodeError(DiagId.UNSUP_RANGE_ARGS)

    try:
        args = tuple(arg.__index__() for arg in args)

        # Compute range size and warn if it's too large
        start = 0
        end = 0
        step = 1
        if len(args) == 1:
            end = args[0]
        elif len(args) == 2:
            start = args[0]
            end = args[1]
        elif len(args) == 3:
            start = args[0]
            end = args[1]
            step = args[2]

        range_length = (abs(end - start) - 1) // abs(step) + 1
        if range_length >= 64:
            warnings.warn(
                f"This static loop has {range_length} iterations, which may be very slow to compile, consider using `cutlass.range(..., unroll_full=True)` instead.",
                category=DSLOptimizationWarning,
                stacklevel=warning_stacklevel,
            )

        return (start, end, step)
    except:
        raise DSLUserCodeError(
            DiagId.ARG_NON_CONSTANT,
        )


def range_value_check(*args: Any) -> tuple[int, int, int]:
    """Ensure all ``range_constexpr`` bounds are compile-time Python integers."""
    # Explicit range_constexpr lowering calls this wrapper directly from the
    # transformed user function. Account for this wrapper plus the helper.
    return _range_value_check(args, warning_stacklevel=3)


@lru_cache(maxsize=1)
def _get_self_module() -> types.ModuleType | None:
    """
    This function is used to get the owning module of this function.
    """
    return inspect.getmodule(_get_self_module)


@lru_cache(maxsize=16)
def cf_symbol_check(symbol: Any) -> None:
    """
    Check if the symbol is control flow symbol from current module.
    """

    failed = False
    name = symbol.__name__
    self_module = _get_self_module()
    if inspect.ismodule(symbol):
        root_module = name.split(".")[0]
        self_root_module = self_module.__name__.split(".")[0]  # type: ignore[union-attr]
        if root_module != self_root_module:
            failed = True
    else:
        owning_module = inspect.getmodule(symbol)
        root_module = owning_module.__name__.split(".")[0]  # type: ignore[union-attr]
        self_root_module = self_module.__name__.split(".")[0]  # type: ignore[union-attr]
        if root_module != self_root_module:
            failed = True

    if failed:
        raise DSLUserCodeError(
            DiagId.CALL_WRONG_IMPORT,
            name=name,
        )


def _any_all_over_generator(
    fcn: Any, redirected: Callable[..., Any], generator: Iterator[Any]
) -> Any:
    """``any()``/``all()`` over a generator, one element at a time: a meta
    element decides exactly like Python (a truthy one ends ``any()``, a falsy
    one ends ``all()``; later elements are never evaluated), and the first
    staged element hands itself and the rest of the generator to the DSL
    reduction.  The elements consumed before it are the ones that did not
    decide, so leaving them out of that reduction cannot change its result.
    """
    assert executor._is_dynamic_expression, "Executor.set_functions() has not run"
    decides = fcn is builtins.any
    for item in generator:
        if executor._is_dynamic_expression(item):
            return redirected((item, *generator))
        if bool(item) is decides:
            return decides
    return not decides


def _call_redirected_builtin(fcn: Any, *args: Any, **kwargs: Any) -> Any:
    """Call the DSL's stand-in for the built-in *fcn* (``Executor.set_functions``).

    The stand-in chooses between the DSL reduction and the native built-in by
    looking for staged values inside tuple/list arguments.  A generator argument
    is opaque to that check, so ``max(x for x in t)`` reached the native
    built-in, whose truth test of a staged Boolean fails.  ``max()``/``min()``
    consume the whole generator anyway, so it is materialised into a tuple
    first (exact, keywords included); ``any()``/``all()`` are evaluated lazily
    to keep Python's short-circuit for meta elements.
    """
    assert executor._builtin_redirector, "Executor.set_functions() has not run"
    redirected = executor._builtin_redirector(fcn)
    if len(args) == 1 and isinstance(args[0], types.GeneratorType):
        if fcn is builtins.max or fcn is builtins.min:
            return redirected(tuple(args[0]), **kwargs)
        if (fcn is builtins.any or fcn is builtins.all) and not kwargs:
            return _any_all_over_generator(fcn, redirected, args[0])
    return redirected(*args, **kwargs)


def redirect_builtin_function(fcn: Any) -> Any:
    """
    This function is used to redirect built-in function call
    to the function defined in DSL package.
    """
    # Only redirect if it's a built-in
    if fcn is builtins.bool:
        return bool_cast

    if isinstance(fcn, BuiltinFunctionType):
        if fcn in [builtins.exec, builtins.eval]:
            raise DSLUserCodeError(
                DiagId.UNSUP_BUILTIN,
                name=fcn.__name__,
            )
        if executor._builtin_redirector:
            return partial(_call_redirected_builtin, fcn)
    return fcn


def copy_members(dest: object, src: object) -> None:
    """
    Copies all non-callable, non-dunder members from src to dest if they exist in src.
    Skips members that are callables or have names starting with double underscores.
    """
    if id(dest) == id(src):
        return

    members = getmembers(dest)
    for name, value in members:
        if (
            name.startswith("__")
            or isinstance(value, Callable)  # type: ignore[arg-type]
            or not hasattr(src, name)
        ):
            continue
        try:
            setattr(dest, name, getattr(src, name))
        except AttributeError:
            # AttributeError means the member is no settable, like property without setter, just ignore
            pass


def get_locals_or_none(locals: dict[str, Any], symbols: list[str]) -> list[Any]:
    """
    Given a locals() dictionary and a list of symbol names, return a list of their values
    in the same order as the symbols list. If a symbol is not present in locals, None is returned
    for that symbol.
    """
    variables = []
    for symbol in symbols:
        if symbol in locals:
            variables.append(locals[symbol])
        else:
            variables.append(None)
    return variables


def closure_check(
    closures: list[Any], _visited: set[tuple[str, int]] | None = None
) -> None:
    """
    Check if the closures have any unsupported capture.
    """

    if _visited is None:
        _visited = set()

    for closure in closures:
        # Use (function name, id) as identity to skip already-processed closures
        # and prevent infinite recursion with mutually-recursive captured functions
        closure_identity = (closure.__name__, id(closure))
        if closure_identity in _visited:
            continue
        _visited.add(closure_identity)

        closure_vars = inspect.getclosurevars(closure)
        for name, value in closure_vars.nonlocals.items():
            if inspect.ismodule(value):
                continue
            if inspect.isfunction(value) or inspect.ismethod(value):
                closure_check([value], _visited)
                continue
            raise DSLUserCodeError(
                DiagId.SCOPE_CLOSURE_CAPTURE,
                func_name=closure.__name__,
                var_name=name,
            )


# cute.printf format strings.  Both spellings -- ``cute.printf("{:04d}", n)``
# and ``cute.printf(f"{n:04d}")`` -- lower to a C printf whose C++ lowering only
# knows two things: a bare ``{}`` (replaced, in operand order, by the operand's
# own conversion: %d/%lld/%u/%llu/%f or a layout's expansion) and the ``%``
# conversions already in the string.  Every Python-flavoured piece of a field
# is therefore resolved here, at trace time, where the operand types are known:
# a ``{:spec}`` becomes a width/sign-correct C conversion, and once a ``%``
# conversion precedes a ``{}`` the remaining numeric ``{}`` are made explicit
# too, because the lowering fills the *first remaining* ``{}`` for each
# operand and would otherwise hand operand i's conversion to operand i+1's slot.

_FORMAT_SPEC_RE = re.compile(
    r"^(?:(?P<fill>.)?(?P<align>[<>=^]))?(?P<sign>[-+ ])?(?P<z>z)?(?P<alt>#)?"
    r"(?P<zero>0)?(?P<width>\d+)?(?P<grouping>[,_])?(?:\.(?P<precision>\d+))?"
    r"(?P<type>[a-zA-Z%])?$"
)
# A complete C conversion (``%%`` included); anything else after a ``%`` is a
# stray percent sign that printf would mis-read.
_C_CONVERSION_RE = re.compile(
    r"%(?:%|[-+ #0]*\d*(?:\.\d+)?(?:hh|h|ll|l|j|z|t|L)?[diouxXeEfFgGaAcsp])"
)
_CONVERSION_WARNING = "Conversion may not be honored for dynamic expressions"


class PreparedFormat(str):
    """A cute.printf format string already lowered to C conventions.

    ``fstring_decompose`` returns one so that ``cute.printf`` skips the Python
    ``str.format``-style parse (the f-string text is Python text, not a format
    string) and only checks the placeholder count.
    """


class _PrintfField(NamedTuple):
    arg_index: int
    conversion: str | None  # None: a bare ``{}`` left for the lowering to fill


def _printf_scalar_info(value: object) -> tuple[str, int, bool] | None:
    """``(kind, width, signed)`` of a numeric printf operand, None otherwise."""
    from .typing import Float, Integer

    if isinstance(value, bool):
        return ("int", 1, True)
    if isinstance(value, int):
        return ("int", 32, True)
    if isinstance(value, float):
        return ("float", 32, True)
    cls = type(value)
    if issubclass(cls, Integer):
        return ("int", cls.width, bool(cls.signed))
    if issubclass(cls, Float):
        return ("float", cls.width, True)
    from .._mlir import ir

    if isinstance(value, ir.Value):
        ty = value.type
        if ir.IntegerType.isinstance(ty):
            return ("int", ir.IntegerType(ty).width, True)
        if ir.FloatType.isinstance(ty):
            return ("float", ir.FloatType(ty).width, True)
    return None


def _printf_bare_conversion(info: tuple[str, int, bool]) -> str | None:
    """The conversion the lowering itself would pick for a bare ``{}``."""
    kind, width, signed = info
    if kind == "float":
        return "%f"
    if width > 64:
        return None
    return "%" + ("ll" if width == 64 else "") + ("d" if signed else "u")


def _printf_spec_conversion(spec: object, value: object) -> str:
    """Translate a Python format spec into the C conversion for ``value``."""

    def refuse(reason: str) -> DSLUserCodeError:
        return DSLUserCodeError(
            DiagId.PRINTF_UNSUPPORTED_SPEC, spec=spec, reason=reason
        )

    if not isinstance(spec, str) or "{" in spec or "}" in spec:
        raise refuse("a nested replacement field can't be resolved at trace time")
    m = _FORMAT_SPEC_RE.match(spec)
    if m is None:
        raise refuse("it isn't a valid format spec")
    info = _printf_scalar_info(value)
    if info is None:
        raise refuse("format specs apply to numeric values only")
    if m["align"]:
        raise refuse("alignment (<, >, ^, =) can't be applied to a runtime value")
    if m["grouping"]:
        raise refuse("digit grouping (`,` / `_`) isn't a printf feature")
    if m["z"]:
        raise refuse("the `z` option isn't a printf feature")
    kind, width, signed = info
    type_char = m["type"]
    length = ""
    if kind == "int":
        if type_char in (None, "d", "n"):
            letter = "d" if signed else "u"
        elif type_char in ("x", "X", "o"):
            letter = type_char
        elif type_char == "c" and width <= 32:
            letter = "c"
        elif type_char in ("e", "E", "f", "F", "g", "G", "%"):
            raise refuse("a float conversion on an integer value; convert it first")
        else:
            raise refuse(f"`{type_char}` isn't a printf conversion for an integer")
        if m["precision"] is not None:
            raise refuse("precision isn't allowed on an integer value")
        if width > 64:
            raise refuse("values wider than 64 bits have no printf conversion")
        length = "ll" if width == 64 else ""
    else:
        if type_char is None:
            letter = "g"
        elif type_char in ("e", "E", "f", "F", "g", "G"):
            letter = type_char
        else:
            raise refuse(f"`{type_char}` isn't a printf conversion for a float")
    sign = m["sign"] if m["sign"] in ("+", " ") else ""
    precision = "" if m["precision"] is None else "." + m["precision"]
    return (
        "%"
        + sign
        + (m["alt"] or "")
        + (m["zero"] or "")
        + (m["width"] or "")
        + precision
        + length
        + letter
    )


def _printf_literal_conversions(text: str) -> int:
    """Count the C conversions in literal text; refuse a stray ``%``."""
    count = 0
    pos = text.find("%")
    while pos >= 0:
        m = _C_CONVERSION_RE.match(text, pos)
        if m is None:
            raise DSLUserCodeError(
                DiagId.PRINTF_UNSUPPORTED_SPEC,
                spec=text[pos : pos + 4],
                reason="a `%` starts a printf conversion; write a literal "
                "percent sign as `%%`",
            )
        if m.group() != "%%":
            count += 1
        pos = text.find("%", m.end())
    return count


def count_printf_placeholders(fmt: str) -> int:
    """Placeholders the lowering will fill: bare ``{}`` and ``%`` conversions.

    Mirrors ``identifyUnsignedFormats`` in the C++ lowering so the count agrees
    with the varargs the generated printf consumes.
    """
    count = 0
    i = 0
    n = len(fmt)
    while i < n:
        if fmt[i] == "{" and i + 1 < n and fmt[i + 1] == "}":
            count += 1
            i += 2
            continue
        if fmt[i] == "%" and i + 1 < n:
            if fmt[i + 1] == "%":
                i += 2
                continue
            i += 1
            while i < n and fmt[i] in "-+ #0":
                i += 1
            while i < n and fmt[i].isdigit():
                i += 1
            if i < n and fmt[i] == ".":
                i += 1
                while i < n and fmt[i].isdigit():
                    i += 1
            if i < n and fmt[i] in "hljztL":
                if fmt[i] == "l" and i + 1 < n and fmt[i + 1] == "l":
                    i += 1
                i += 1
            if i < n:
                count += 1
        i += 1
    return count


def _render_printf_format(
    pieces: list[str | _PrintfField], operands: Sequence[object]
) -> str:
    out: list[str] = []
    saw_conversion = False
    for piece in pieces:
        if isinstance(piece, str):
            out.append(piece)
            saw_conversion |= _printf_literal_conversions(piece) > 0
            continue
        if piece.conversion is not None:
            out.append(piece.conversion)
            saw_conversion = True
            continue
        if not saw_conversion:
            out.append("{}")
            continue
        info = _printf_scalar_info(operands[piece.arg_index])
        conversion = _printf_bare_conversion(info) if info is not None else None
        if conversion is None:
            raise DSLUserCodeError(
                DiagId.PRINTF_UNSUPPORTED_SPEC,
                spec="{}",
                reason="a `{}` for a non-numeric value can't follow a formatted "
                "field or `%` conversion; move it in front of them or use a "
                "separate cute.printf",
            )
        out.append(conversion)
    return "".join(out)


def translate_printf_format(fmt: str, operands: Sequence[object]) -> str:
    """Lower a ``cute.printf`` format string to what the lowering expects.

    Refuses what the generated printf can't honor (positional/named fields,
    brace escapes, stray ``%``) and translates ``{:spec}`` fields into
    width/sign-correct C conversions for their operands.
    """
    try:
        parsed = list(string.Formatter().parse(fmt))
    except ValueError as e:
        raise DSLUserCodeError(
            DiagId.PRINTF_BRACE_ESCAPE_UNSUPPORTED,
            detail=f"the format string has an unbalanced brace ({e})",
        ) from e
    pieces: list[str | _PrintfField] = []
    expected = 0
    for literal, field_name, spec, conversion in parsed:
        if literal:
            if "{" in literal or "}" in literal:
                raise DSLUserCodeError(
                    DiagId.PRINTF_BRACE_ESCAPE_UNSUPPORTED,
                    detail="the format string uses `{{` / `}}` escapes",
                )
            expected += _printf_literal_conversions(literal)
            pieces.append(literal)
        if field_name is None:
            continue
        if field_name != "":
            raise DSLUserCodeError(
                DiagId.PRINTF_POSITIONAL_FIELD,
                field="{" + field_name + (f":{spec}" if spec else "") + "}",
            )
        if spec and ("{" in spec or "}" in spec):
            raise DSLUserCodeError(
                DiagId.PRINTF_UNSUPPORTED_SPEC,
                spec=spec,
                reason="a nested replacement field can't be resolved at trace time",
            )
        pieces.append(_PrintfField(expected, spec or None))
        expected += 1
        if conversion is not None:
            warnings.warn(_CONVERSION_WARNING, stacklevel=4)
    if expected != len(operands):
        raise DSLUserCodeError(
            DiagId.PRINTF_ARG_COUNT_MISMATCH, expected=expected, got=len(operands)
        )
    pieces = [
        p
        if isinstance(p, str) or p.conversion is None
        else _PrintfField(
            p.arg_index, _printf_spec_conversion(p.conversion, operands[p.arg_index])
        )
        for p in pieces
    ]
    return _render_printf_format(pieces, operands)


def check_printf_placeholder_count(fmt: str, n_operands: int) -> None:
    """Refuse a format string whose placeholder count differs from its operands."""
    expected = count_printf_placeholders(fmt)
    if expected != n_operands:
        raise DSLUserCodeError(
            DiagId.PRINTF_ARG_COUNT_MISMATCH, expected=expected, got=n_operands
        )


@dataclass
class FormattedValue:
    """
    Represents a value (from an f-string interpolation) along with its conversion and format specification.

    This is a runtime representation of ast.FormattedValue.
    See https://docs.python.org/3/library/ast.html#ast.FormattedValue

    This class is used to encapsulate a value that is to be embedded into an f-string formatted string,
    along with any conversion flags (such as '!s', '!r', or '!a') and a list of format specification strings
    (e.g., '.2f', '05d', etc).

    Attributes:
        value (Any): The value to be formatted.
        conversion (int): The ASCII code of the conversion character, defaulting to -1 (no conversion).
        format_spec (Optional[List[str]]): List of format specifier strings.
    """

    value: Any
    conversion: int = -1
    format_spec: list[str] | None = None

    def to_str(self) -> tuple[str, Any | None]:
        """
        Converts the FormattedValue into a format string component and (optional) dynamic argument.

        If the value is a dynamic expression (requires runtime evaluation), returns a printf-style placeholder and
        the corresponding dynamic value for later substitution. For static (non-dynamic) values, returns the fully
        rendered literal string and None for the dynamic value.

        Returns:
            Tuple[str, Optional[Any]]: A tuple where the first element is the format string component and the second
            element is the dynamic value (or None if not required).

        Raises:
            DSLRuntimeError: If the format spec is invalid or not supported for dynamic expressions.
        """
        if executor._is_dynamic_expression(self.value):  # type: ignore[misc]
            if self.conversion != -1:
                warnings.warn(_CONVERSION_WARNING, stacklevel=3)
            if self.format_spec and (
                len(self.format_spec) > 1 or not isinstance(self.format_spec[0], str)
            ):
                raise DSLUserCodeError(
                    DiagId.UNSUP_FSTRING_FORMAT,
                )
            if self.format_spec:
                spec = self.format_spec[0]
                m = _FORMAT_SPEC_RE.match(spec)
                if spec.startswith(("<", ">", "^")) or (m is not None and m["align"]):
                    raise DSLUserCodeError(
                        DiagId.UNSUP_FSTRING_ALIGN,
                    )
                return _printf_spec_conversion(spec, self.value), self.value
            return "{}", self.value
        else:
            conversion_str = ""
            if self.conversion == 97:
                conversion_str = "!a"  # ASCII
            elif self.conversion == 114:
                conversion_str = "!r"  # repr
            elif self.conversion == 115:
                conversion_str = "!s"  # str
            if self.format_spec is not None:
                f_str = f"{{{conversion_str}:{self.format_spec[0]}}}"
            else:
                f_str = f"{{{conversion_str}}}"
            return f_str.format(self.value), None


def fstring_decompose(
    joinedStrComponent: list[str | FormattedValue],
) -> tuple[Any, ...]:
    """
    Decomposes a joined f-string component list into a format string and dynamic arguments.

    This function takes a sequence of components representing parts of an f-string,
    which may include both literal strings and FormatValue instances.
    It assembles a format string with placeholders for dynamic values
    and collects the actual dynamic argument values in order.

    Args:
        joinedStrComponent (List[Union[str, FormattedValue]]): The components of the f-string.

    Returns:
        Tuple[str, ...]: A tuple containing the format string as the first element,
                         followed by all dynamic argument values.

    Raises:
        DSLUserCodeError: If an unsupported component type is encountered.
    """
    pieces: list[str | _PrintfField] = []
    dynamic_args: list[Any] = []

    def literal(text: str, what: str) -> str:
        # f-string text is Python text: a `%` is a percent sign, and a `{}`
        # (written `{{}}`) would be filled by the lowering like a placeholder.
        if "{}" in text:
            raise DSLUserCodeError(
                DiagId.PRINTF_BRACE_ESCAPE_UNSUPPORTED,
                detail=f"{what} contains a literal `{{}}`",
            )
        return text.replace("%", "%%")

    for component in joinedStrComponent:
        if isinstance(component, FormattedValue):
            s, v = component.to_str()
            if v is None:
                pieces.append(literal(s, "a value rendered into the f-string"))
            else:
                # This is a dynamic value, add to dynamic_args
                pieces.append(_PrintfField(len(dynamic_args), None if s == "{}" else s))
                dynamic_args.append(v)
        elif isinstance(component, str):
            pieces.append(literal(component, "the f-string text"))
        else:
            raise DSLUserCodeError(DiagId.UNSUP_FSTRING)
    return (PreparedFormat(_render_printf_format(pieces, dynamic_args)), *dynamic_args)
