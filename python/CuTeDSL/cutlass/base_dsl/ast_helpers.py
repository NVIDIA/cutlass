class range_constexpr:
    """A trace-time range that delegates iteration to Python's builtin range."""

    def __init__(self, *args: Any) -> None:
        # Runtime-dispatched aliases reach this constructor through additional
        # materialization frames, so retain their existing warning attribution.
        self.args = _range_value_check(args, warning_stacklevel=4)

    def __iter__(self) -> Iterator[int]:
        return iter(builtins.range(*self.args))


def is_dynamic_range(value: object) -> bool:
    """Return whether a trace-time iterable should lower to a staged loop."""
    return isinstance(value, (builtins.range, range))


_deferred_for_errors: dict[int, BaseException] = {}
_deferred_for_error_ids = itertools.count()


def register_deferred_for_error(error: BaseException) -> int:
    """Retain a speculative dynamic-loop error until trace-time dispatch."""
    error_id = next(_deferred_for_error_ids)
    # Entries outlive the trace, so a traceback would pin every caller's locals.
    error.__traceback__ = None
    _deferred_for_errors[error_id] = error
    return error_id


def raise_deferred_for_error(error_id: int) -> None:
    """Raise an error selected by dynamic dispatch.

    Keep the registered exception because a preprocessed function can be
    traced more than once, and every dynamic selection must report the same
    frontend diagnostic.
    """
    raise _deferred_for_errors[error_id]


def discard_deferred_for_error(error_id: int) -> None:
    """Release an error from an unselected dynamic branch."""
    _deferred_for_errors.pop(error_id, None)


def materialize_for_iter(factory: Callable[..., Any], *args: Any, **kwargs: Any) -> Any:
    """Construct a call-form iterable without invoking staged ``range``."""
    if factory is range_dynamic:
        _warn_deprecated(_RANGE_DYNAMIC_DEPRECATION, every_call=True)
    if factory is builtins.range or factory is range_dynamic or factory is range:
        return range(*args, **kwargs)

    return factory(*args, **kwargs)


