def assert_executor(test: Any, msg: str | None = None) -> None:
    """A bare ``assert`` in a traced body is a compile-time check: a Meta
    condition runs as a real Python ``assert`` (Python parity, ``AssertionError``
    with the message); a Staged condition is refused -- ``cutlass.assert_`` is
    the run-time form."""
    from .typing import Numeric

    fail = False
    # Implicit convert dynamic expression to bool is not allowed
    # So here explicitly do a None check
    if test is not None and executor._is_dynamic_expression(test):  # type: ignore[misc]
        if isinstance(test, Numeric):
            try:
                test = test.to(bool)
            except:
                fail = True
        else:
            fail = True

    if not fail:
        assert test, msg
    else:
        raise DSLUserCodeError(DiagId.ASSERT_DYNAMIC_CONDITION)


def bool_short_circuits(value: Any, short_circuit_value: bool) -> bool:
    """True when the and/or LHS *value* short-circuits in Python: it is a
    Python-truth bool -- a plain ``bool``, or a wrapper DECLARING a bool
    payload through ``_pyir_raw_payload`` -- whose truth equals
    *short_circuit_value*.  A staged or non-bool value answers False, so the
    rewrite's other arm evaluates (the ``and_``/``or_`` helper)."""
    if type(value) is bool:
        return value == short_circuit_value
    payload = getattr(value, "_pyir_raw_payload", None)
    if type(payload) is bool:
        return payload == short_circuit_value
    return False


def bool_cast(value: Any) -> bool:
    from .typing import Numeric

    truth = truth_of(value)
    if isinstance(truth, (Numeric, ir.Value)):
        raise DSLUserCodeError(
            DiagId.PHASE_REQUIRES_CONSTANT,
            what="Explicit boolean conversion",
        )
    if isinstance(truth, bool):
        return truth
    # A Python number's (or a watched wrapper's) own truth test; the boundary
    # observes it like any user object's ``__bool__``.
    from .pyir_callee_rewrite import _pyir_boundary_observe_truth

    return _pyir_boundary_observe_truth(truth)


def _pyir_const_expr_operand(value: object) -> object:
    """The declared trace-time payload of one ``const_expr(...)`` operand: a
    compiler-tracked META wrapper is consumed through the call-boundary funnel
    (recorded, and loud on a promoted place); anything else passes through."""
    from .pyir_runtime import _WatchedM

    if not isinstance(value, _WatchedM):
        return value
    from .pyir_runtime import _pyir_boundary_consume_meta_arg

    return _pyir_boundary_consume_meta_arg(value, compare_executor)


def _refuses_staged_truth(test: Any) -> bool:
    """Whether Python's truth test of *test* raises the context-free
    ``PHASE_DYNAMIC_TO_STATIC_BOOL``: a numeric value carrying no trace-time
    payload (the rule of ``Numeric.__bool__``).  A pure predicate -- the truth
    test itself stays in the author's frame, so payload witnesses and a user
    object's own ``__bool__`` run exactly as without the guard."""
    from .typing import is_staged_numeric

    return is_staged_numeric(test)


def native_exit_guard(test: Any, kind: str) -> Any:
    """The test of an ``if`` kept as plain Python because it owns a ``break`` /
    ``continue`` / ``return`` of a loop unrolled at compile time: a runtime
    condition cannot decide that exit, so refuse with the construct's own
    diagnostic instead of the context-free truth-test one.  Returns *test*."""
    if _refuses_staged_truth(test):
        raise DSLUserCodeError(DiagId.UNSUP_EARLY_EXIT_RUNTIME_CONDITION, kind=kind)
    return test


def comprehension_condition(test: Any) -> Any:
    """The test of a comprehension ``if`` clause: the filter runs in Python at
    compile time and the result's length would follow a runtime value, so a
    staged condition is refused like a built-in's truth test.  Returns *test*."""
    if _refuses_staged_truth(test):
        raise DSLUserCodeError(
            DiagId.PHASE_NATIVE_CALLEE_STAGED_TRUTH,
            callee="a comprehension `if` clause",
        )
    return test


def compare_executor(
    left: Any,
    comparators: list[Any],
    ops: list[Any],
    const_expr: bool = False,
) -> Any:
    """
    Executes comparison operations with a left operand and a list of comparators.

    Args:
        left: The leftmost value in the comparison chain
        comparators: A list of values to compare against
        ops: A list of comparison operators to apply
        const_expr: The comparison is written inside ``const_expr(...)``, which
            declares every operand a trace-time constant

    Returns:
        The result of the comparison chain

    Raises:
        AssertionError: If the executor function is not set before execution
    """
    assert executor._compare_executor is not None, (
        "Function must be set before execution."
    )
    if "is" in ops or "is not" in ops:
        if const_expr:
            # Declared trace-time constant: the identity leg is asked about the
            # PAYLOADS the un-traced program holds, so consume every watched
            # META operand through the boundary funnel and compare those. The
            # funnel refuses a place promoted to a staged cell -- there
            # ``const_expr`` has no compile-time value to answer with. Operands
            # the declaration cannot cover (a staged, ir-backed wrapper) stay
            # untouched and still meet the choke below.
            left = _pyir_const_expr_operand(left)
            comparators = [_pyir_const_expr_operand(c) for c in comparators]
        # Identity legs over tracker-minted wrappers refuse-or-witness
        # (LangRef 3.12 section 6.10.3); inert outside a PyIR trace scope, and
        # inert over the plain payloads the funnel just handed back.
        from .pyir_core import _pyir_identity_compare_choke

        _pyir_identity_compare_choke(left, comparators, ops)
    result = executor._compare_executor(left, comparators, ops)
    # Gate-once evidence (see pyir_state): record only the provable membership-gate
    # shape (one ``not in`` over a plain set); clear on every other comparison.
    try:
        from .pyir_runtime import _PYIR_LAST_NOTIN_COMPARE

        if (
            len(ops) == 1
            and ops[0] == "not in"
            and type(result) is bool
            and type(left) in (str, int, bool)
            and type(comparators[0]) is set
        ):
            _PYIR_LAST_NOTIN_COMPARE[0] = (comparators[0], left, result)
        else:
            _PYIR_LAST_NOTIN_COMPARE[0] = None
    except Exception:
        pass
    return result


def traced_attr_read(owner: object, attr: str) -> Any:
    """Read ``owner.attr`` the way the instrumented frame reads it.

    A DSL funnel that consumes an object's fields on the program's behalf
    (``cutlass.equal`` over a dataclass) must not ``getattr`` them raw: under
    PyIR the frame's own ``obj.attr`` goes through the attribute-read choke,
    which serves a loop-carried holder's carried leaf (a ``while`` condition
    otherwise compares the pre-loop value forever).  The legacy frontend
    reads the attribute directly.
    """
    if is_pyir_enabled():
        return _pyir_post_attr_read(f"{type(owner).__name__}.{attr}", owner, attr)
    return getattr(owner, attr)


