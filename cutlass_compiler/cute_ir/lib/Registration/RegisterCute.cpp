using namespace mlir;

namespace mlir::cutlass_compiler::cute {

void registerCuteDialects(DialectRegistry &registry) {
  registry.insert<arith::ArithDialect, func::FuncDialect, gpu::GPUDialect,
                  LLVM::LLVMDialect, math::MathDialect, scf::SCFDialect,
                  ub::UBDialect, CuteDialect>();
}

void registerCutePasses() {
  registerCuteTransformsPasses();
  registerCuteConversionPasses();
}

} // namespace mlir::cutlass_compiler::cute
